"""Regenerate the manuscript inter-rater table from the deposited LIDC consolidation.

Fills ``tab:irr_v05`` from ``annotations/lidc_majority_vote/{patient_id}.json``. Each
consensus nodule records how many of the four LIDC readers contributed to it
(``n_contributing_readers`` in {3, 4} under the >=3-of-4 threshold, or 1..4 if a looser
consolidation is used). Every reported number is *computed* here, which structurally
prevents the class of error flagged in the manuscript (a stated "mean per patient" that
did not equal consensus_nodules / annotated_patients): that mean is now a division, not a
typed-in constant.

Usage:
    python extract_inter_rater.py \
        --majority-vote /path/pwm_ldct_1_0/annotations/lidc_majority_vote \
        [--n-patients-total 1010] --out tables
"""
from __future__ import annotations

import argparse
import glob
import json
import math
import os
from collections import Counter
from typing import Any, Dict, List, Optional

from common import write_outputs

N_LIDC_READERS = 4


def _nodule_contributors(nodule: Dict[str, Any]) -> int:
    """Contributing-reader count for one consensus nodule.

    Prefers the explicit ``n_contributing_readers``; falls back to the length of a
    ``contributing_readers`` list. Raises if neither is present -- the consolidation step
    records this, so its absence means the wrong file was passed, not a silent default.
    """
    if "n_contributing_readers" in nodule:
        return int(nodule["n_contributing_readers"])
    if isinstance(nodule.get("contributing_readers"), list):
        return len(nodule["contributing_readers"])
    raise ValueError(
        "consensus nodule lacks n_contributing_readers / contributing_readers; "
        "regenerate the majority-vote files with the consolidation reference impl."
    )


def compute_inter_rater(majority_vote_dir: str,
                        n_patients_total: Optional[int] = None) -> Dict[str, Any]:
    files = sorted(glob.glob(os.path.join(majority_vote_dir, "*.json")))
    if not files:
        raise FileNotFoundError(f"no majority-vote JSON under {majority_vote_dir}")

    patients_with_nodule = 0
    max_per_patient = 0
    contrib = Counter()          # n_contributing_readers -> count of consensus nodules
    pairwise_agree_sum = 0.0     # sum over nodules of C(k,2)/C(R,2)
    total_pairs = math.comb(N_LIDC_READERS, 2)

    for path in files:
        with open(path, "r", encoding="utf-8") as fh:
            record = json.load(fh)
        nodules = record.get("nodules", record if isinstance(record, list) else [])
        if nodules:
            patients_with_nodule += 1
            max_per_patient = max(max_per_patient, len(nodules))
        for nod in nodules:
            k = _nodule_contributors(nod)
            contrib[k] += 1
            pairwise_agree_sum += math.comb(k, 2) / total_pairs

    consensus_nodules = sum(contrib.values())
    patients_total = n_patients_total if n_patients_total is not None else len(files)
    mean_contrib = (sum(k * n for k, n in contrib.items()) / consensus_nodules
                    if consensus_nodules else 0.0)

    return {
        "patients_total": patients_total,
        "patients_with_consensus_nodule": patients_with_nodule,
        "consensus_nodules": consensus_nodules,
        # computed, not asserted -- this division is what the manuscript caption must show:
        "mean_nodules_per_annotated_patient": (consensus_nodules / patients_with_nodule
                                               if patients_with_nodule else 0.0),
        "max_nodules_per_patient": max_per_patient,
        "mean_contributing_readers": mean_contrib,
        "reader_agreement_fraction": mean_contrib / N_LIDC_READERS,
        "pairwise_agreement": (pairwise_agree_sum / consensus_nodules
                               if consensus_nodules else 0.0),
        "contributing_distribution": {str(k): contrib[k] for k in sorted(contrib)},
    }


def to_latex(t: Dict[str, Any]) -> str:
    dist = t["contributing_distribution"]
    def pct(n): return f"{100.0 * n / t['consensus_nodules']:.1f}\\%" if t["consensus_nodules"] else "---"
    lines = [
        "% auto-generated by extract_inter_rater.py -- do not hand-edit",
        "\\textbf{Cohort} & \\textbf{Patients} & \\textbf{Consensus nodules} "
        "& \\textbf{Mean contrib.\\ readers} & \\textbf{Pairwise agreement} \\\\",
        "\\midrule",
        (f"LIDC-IDRI (deposited) & {t['patients_total']:,} & {t['consensus_nodules']:,} "
         f"& {t['mean_contributing_readers']:.2f} / {N_LIDC_READERS} "
         f"({100.0 * t['reader_agreement_fraction']:.1f}\\%) "
         f"& {100.0 * t['pairwise_agreement']:.1f}\\% \\\\"),
        (f"\\hspace{{1em}}of which: $\\geq 1$ consensus nodule & {t['patients_with_consensus_nodule']:,} "
         f"& --- & --- & --- \\\\"),
    ]
    for k in sorted(dist, key=int, reverse=True):
        lines.append(f"\\hspace{{1em}}distribution: {k}/{N_LIDC_READERS} readers "
                     f"& --- & {dist[k]:,} ({pct(dist[k])}) & --- & --- \\\\")
    # a self-check comment so the reader can see the mean is consistent:
    lines.append(f"% check: {t['consensus_nodules']} nodules / "
                 f"{t['patients_with_consensus_nodule']} annotated patients "
                 f"= {t['mean_nodules_per_annotated_patient']:.2f} per patient "
                 f"(max {t['max_nodules_per_patient']})")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--majority-vote", required=True)
    ap.add_argument("--n-patients-total", type=int, default=None,
                    help="total LIDC patients (default: number of majority-vote files)")
    ap.add_argument("--out", default="tables")
    args = ap.parse_args()
    table = compute_inter_rater(args.majority_vote, args.n_patients_total)
    write_outputs("inter_rater", table, to_latex(table), args.out)
    print(f"inter_rater: {table['consensus_nodules']} nodules / "
          f"{table['patients_with_consensus_nodule']} annotated patients "
          f"= {table['mean_nodules_per_annotated_patient']:.2f}/patient")


if __name__ == "__main__":
    main()
