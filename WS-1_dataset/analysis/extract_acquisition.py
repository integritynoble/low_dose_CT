"""Regenerate the manuscript acquisition table from ``metadata/*.json``.

Fills ``tab:acquisition_v05``: per-source manufacturer split, scanner models, typical
kVp, effective-mAs median/range, pitch, thin-slice thickness range, reconstruction
kernels. All computed here from the deposited ``acquisition`` blocks (schema §5) -- this
is the committed extraction the acquisition caption references, so the "provisional"
LIDC/AAPM rows fill deterministically once their harmonized builds run.

Usage:
    python extract_acquisition.py --metadata /path/pwm_ldct_1_0/metadata --out tables
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from typing import Any, Dict, List

from common import (SOURCES, count_categories, fmt_range, latex_escape,
                    load_series_metadata, summarize_numeric, write_outputs)


def compute_acquisition(series_list: List[Dict[str, Any]]) -> Dict[str, Any]:
    by_source: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for s in series_list:
        by_source[s["source"]].append(s.get("acquisition") or {})

    def summarize(acqs: List[Dict[str, Any]]) -> Dict[str, Any]:
        mfr = count_categories(a.get("manufacturer") for a in acqs)
        kvp = count_categories(a.get("kvp") for a in acqs)
        kernel = count_categories(a.get("recon_kernel") for a in acqs)
        model = count_categories(a.get("model") for a in acqs)
        return {
            "n_series": len(acqs),
            "manufacturer": dict(mfr.most_common()),
            "models": dict(model.most_common()),
            "kvp": dict(kvp.most_common()),
            "kvp_typical": kvp.most_common(1)[0][0] if kvp else None,
            "exposure_mas": summarize_numeric(a.get("exposure_mas") for a in acqs),
            "pitch": summarize_numeric(a.get("pitch") for a in acqs),
            "slice_thickness_mm": summarize_numeric(a.get("slice_thickness_mm") for a in acqs),
            "recon_kernels": dict(kernel.most_common()),
        }

    return {src: summarize(by_source[src]) for src in SOURCES if by_source.get(src)}


def _mfr_str(mfr: Dict[str, int]) -> str:
    if not mfr:
        return "N/A"
    parts = [f"{k} ({v})" for k, v in mfr.items()]
    return latex_escape(", ".join(parts))


def to_latex(table: Dict[str, Any]) -> str:
    cols = [s for s in SOURCES if s in table]
    header = " & ".join(["\\textbf{Parameter}"] + [f"\\textbf{{{c.upper()}}}" for c in cols])
    rows = [header + " \\\\", "\\midrule"]

    def row(label: str, render) -> str:
        return f"{label} & " + " & ".join(render(table[c]) for c in cols) + " \\\\"

    rows.append(row("Manufacturer set", lambda d: _mfr_str(d["manufacturer"])))
    rows.append(row("Tube voltage (kVp), typical", lambda d: str(d["kvp_typical"]) if d["kvp_typical"] else "N/A"))
    rows.append(row("Full-dose effective mAs, median (range)",
                    lambda d: (f"{d['exposure_mas']['median']:.0f} "
                               f"({fmt_range(d['exposure_mas'], 0)})") if d["exposure_mas"]["n"] else "N/A"))
    rows.append(row("Pitch, typical",
                    lambda d: f"{d['pitch']['median']:.2f}" if d["pitch"]["n"] else "N/A"))
    rows.append(row("Slice thickness (mm), thin series", lambda d: fmt_range(d["slice_thickness_mm"], 2)))
    rows.append(row("Reconstruction kernel(s)",
                    lambda d: latex_escape(", ".join(list(d["recon_kernels"])[:4]) or "N/A")))
    return "% auto-generated by extract_acquisition.py -- do not hand-edit\n" + "\n".join(rows) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metadata", required=True)
    ap.add_argument("--out", default="tables")
    args = ap.parse_args()
    series = load_series_metadata(args.metadata)
    table = compute_acquisition(series)
    write_outputs("acquisition", table, to_latex(table), args.out)
    print(f"acquisition: {len(series)} series across {len(table)} source(s)")


if __name__ == "__main__":
    main()
