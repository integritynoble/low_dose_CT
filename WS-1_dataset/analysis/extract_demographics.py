"""Regenerate the manuscript demographics table from ``metadata/*.json``.

Fills ``tab:demographics_v05``: per-source N (unique patients), age median/IQR/range,
sex M/F counts + %, BMI, scan-year range, indication. Every cell is computed here from
the deposited ``demographics`` blocks (schema §5), so the "provisional" caption flag is
resolved the moment the harmonized builds land.

Usage:
    python extract_demographics.py --metadata /path/pwm_ldct_1_0/metadata --out tables
"""
from __future__ import annotations

import argparse
import os
from collections import Counter, defaultdict
from typing import Any, Dict, List

from common import (SOURCES, count_categories, fmt_median_iqr, fmt_range,
                    load_series_metadata, summarize_numeric, write_outputs)


def _patient_key(series: Dict[str, Any]) -> str:
    prov = series.get("provenance") or {}
    return prov.get("canonical_patient_key") or series.get("patient_id")


def compute_demographics(series_list: List[Dict[str, Any]]) -> Dict[str, Any]:
    """One demographics summary per source + an aggregate, over unique patients."""
    # Deduplicate to one record per (source, canonical patient key): demographics are
    # patient-level, so counting per series would double-count multi-series patients.
    seen: Dict[str, Dict[str, Any]] = {}
    for s in series_list:
        seen.setdefault(f"{s['source']}::{_patient_key(s)}", s)
    per_patient = list(seen.values())

    by_source: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for s in per_patient:
        by_source[s["source"]].append(s)

    def summarize(patients: List[Dict[str, Any]]) -> Dict[str, Any]:
        demo = [p.get("demographics") or {} for p in patients]
        sex = count_categories(d.get("sex") for d in demo)
        n_sex = sum(sex.values())
        return {
            "n_patients": len(patients),
            "age": summarize_numeric(d.get("age_years") for d in demo),
            "sex": {"M": sex.get("M", 0), "F": sex.get("F", 0),
                    "n_known": n_sex, "pct_known": (100.0 * n_sex / len(patients)) if patients else 0.0},
            "bmi": summarize_numeric(d.get("bmi") for d in demo),
            "scan_year": summarize_numeric(d.get("scan_year") for d in demo),
            "indication": Counter(d.get("indication") for d in demo if d.get("indication")),
        }

    out: Dict[str, Any] = {"by_source": {}, "aggregate": summarize(per_patient)}
    for src in SOURCES:
        if by_source.get(src):
            out["by_source"][src] = summarize(by_source[src])
    return out


def to_latex(table: Dict[str, Any]) -> str:
    cols = [s for s in SOURCES if s in table["by_source"]]
    header = " & ".join(["\\textbf{Field}"] + [f"\\textbf{{{c.upper()}}}" for c in cols] + ["\\textbf{Aggregate}"])
    rows = [header + " \\\\", "\\midrule"]

    def cell(src_or_agg: Dict[str, Any], render) -> str:
        return render(src_or_agg)

    def row(label: str, render) -> str:
        vals = [render(table["by_source"][c]) for c in cols] + [render(table["aggregate"])]
        return f"{label} & " + " & ".join(vals) + " \\\\"

    rows.append(row("N (patients, unique)", lambda d: str(d["n_patients"])))
    rows.append(row("Age, median (IQR) [yr]", lambda d: fmt_median_iqr(d["age"], 0)))
    rows.append(row("Age, range [yr]", lambda d: fmt_range(d["age"], 0)))
    rows.append(row("Sex (M / F), n (\\%)",
                    lambda d: f"{d['sex']['M']} / {d['sex']['F']} ({d['sex']['pct_known']:.0f}\\%)"))
    rows.append(row("BMI, median (IQR)", lambda d: fmt_median_iqr(d["bmi"], 1)))
    rows.append(row("Scan-year range", lambda d: fmt_range(d["scan_year"], 0)))
    return "% auto-generated by extract_demographics.py -- do not hand-edit\n" + "\n".join(rows) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metadata", required=True, help="path to the deposited metadata/ dir")
    ap.add_argument("--out", default="tables", help="output dir for {stem}.json/.tex")
    args = ap.parse_args()
    series = load_series_metadata(args.metadata)
    table = compute_demographics(series)
    write_outputs("demographics", table, to_latex(table), args.out)
    print(f"demographics: {len(series)} series -> {table['aggregate']['n_patients']} unique patients")


if __name__ == "__main__":
    main()
